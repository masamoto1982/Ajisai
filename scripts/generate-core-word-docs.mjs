import { readFileSync, writeFileSync } from 'node:fs';

const check = process.argv.includes('--check');
const outputPath = 'rust/src/builtins/generated_core_word_docs.rs';
const words = JSON.parse(readFileSync('spec/words.json', 'utf8'));
const manifest = JSON.parse(readFileSync('docs/word-manifest.json', 'utf8'));
const contracts = new Map(words.entries.filter((word) => !word.module).map((word) => [word.name, word]));
const coreEntries = manifest.entries.filter((entry) => entry.kind === 'coreword');

if (contracts.size !== coreEntries.length) {
  throw new Error(`Core contract count ${contracts.size} does not match manifest count ${coreEntries.length}`);
}

const rustString = (value) => JSON.stringify(value);
const rows = coreEntries.map((entry) => {
  const word = contracts.get(entry.canonical);
  if (!word) throw new Error(`No canonical contract for ${entry.canonical}`);
  return `    GeneratedCoreWordDoc {
        name: ${rustString(word.name)},
        hover_summary: ${rustString(word.documentation.hover)},
        hover_syntax: ${rustString(word.documentation.syntax)},
    },`;
});

const output = `// @generated by scripts/generate-core-word-docs.mjs; do not edit.

pub(crate) struct GeneratedCoreWordDoc {
    pub(crate) name: &'static str,
    pub(crate) hover_summary: &'static str,
    pub(crate) hover_syntax: &'static str,
}

pub(crate) const GENERATED_CORE_WORD_DOCS: &[GeneratedCoreWordDoc] = &[
${rows.join('\n')}
];

pub(crate) fn lookup_generated_core_word_doc(name: &str) -> Option<&'static GeneratedCoreWordDoc> {
    GENERATED_CORE_WORD_DOCS.iter().find(|doc| doc.name == name)
}
`;

if (check) {
  const current = readFileSync(outputPath, 'utf8');
  if (current !== output) {
    console.error(`[core-word-docs] ${outputPath} is stale. Run npm run core-word-docs:generate.`);
    process.exitCode = 1;
  } else {
    console.log(`[core-word-docs] ${coreEntries.length} Core hover contracts are current.`);
  }
} else {
  writeFileSync(outputPath, output);
  console.log(`[core-word-docs] wrote ${coreEntries.length} Core hover contracts to ${outputPath}.`);
}
