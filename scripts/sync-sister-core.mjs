#!/usr/bin/env node
// The shared core with the sister language Arare (tests/sister/arare-shared-core.json).
//
// Arare checks its answers against Ajisai's exact ones (Arare's ADR-0007), so
// what the two languages share is defined twice: by Ajisai's specification and
// by the programs Arare compares. This script copies those programs into
// Ajisai — Arare's oracle corpus and the first PROGRAMS of its seeded,
// generated programs, with the prelude that gives Arare's QUANTIZE, RESCALE,
// NARROW and NEG their exact meanings — and records Ajisai's answer to each.
// rust/tests/sister_core_laws.rs then holds Ajisai to those answers, so a
// change to the shared core shows in Ajisai's CI when it is made, not first
// when Arare next pins the oracle.
//
//   node scripts/sync-sister-core.mjs --arare <path to an Arare checkout>
//       Copies the programs and the prelude from Arare, then records answers.
//   node scripts/sync-sister-core.mjs
//       Keeps the programs and records Ajisai's answers again (after a
//       deliberate change to the shared core, recorded in spec/CHANGELOG.md).
//
// Answers come from `ajisai agent compute` (the agent profile), built here.

import { execFileSync, spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const target = resolve(root, 'tests/sister/arare-shared-core.json');
const PROGRAMS = 2000;

const argAt = process.argv.indexOf('--arare');
const arare = argAt > 0 ? resolve(process.argv[argAt + 1]) : null;

let doc;
if (arare) {
  const corpus = JSON.parse(readFileSync(resolve(arare, 'tests/oracle/corpus.json'), 'utf8'));
  const compare = readFileSync(resolve(arare, 'src/engine/oracle-compare.mjs'), 'utf8');
  const prelude = [...compare.matchAll(/^\s*"(\[ .* \] '[A-Z]+' DEF)",?$/gm)].map((m) => m[1]);
  if (prelude.length === 0) throw new Error('no prelude found in Arare\'s src/engine/oracle-compare.mjs');
  const emitted = execFileSync('node', [resolve(arare, 'scripts/check-oracle-random.mjs'), '--emit'], {
    encoding: 'utf8',
    maxBuffer: 1 << 28,
  });
  const generated = JSON.parse(emitted).slice(0, PROGRAMS);
  const commit = execFileSync('git', ['-C', arare, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  doc = {
    _comment: [
      'Generated by scripts/sync-sister-core.mjs; do not edit by hand. The programs are the sister language',
      "Arare's: its oracle corpus (tests/oracle/corpus.json) and the first programs its seeded generator",
      '(scripts/check-oracle-random.mjs --emit) writes, at the Arare commit below. `prelude` gives Arare\'s',
      "QUANTIZE, RESCALE, NARROW and NEG the exact meanings Arare's oracle comparison gives them. `stack` is",
      "Ajisai's answer, as `ajisai agent compute` displays it, or `error` its category; rust/tests/",
      'sister_core_laws.rs holds Ajisai to every one. A deliberate change to an answer is a change to what',
      'the two languages share: record it in spec/CHANGELOG.md and run this script again.',
    ],
    arare: { commit, generatedPrograms: generated.length },
    prelude,
    cases: [
      ...corpus.cases.map((c) => ({ name: c.name, source: c.source })),
      ...generated.map((source, i) => ({ name: `generated ${i + 1}`, source })),
    ],
  };
} else {
  doc = JSON.parse(readFileSync(target, 'utf8'));
}

execFileSync('cargo', ['build', '--quiet', '--manifest-path', resolve(root, 'rust/Cargo.toml'), '--bin', 'ajisai'], {
  stdio: 'inherit',
});
const bin = resolve(root, 'rust/target/debug/ajisai');
const prelude = doc.prelude.join('\n');
for (const c of doc.cases) {
  const r = spawnSync(bin, ['agent', 'compute', '-', '--compact'], {
    input: `${prelude}\n${c.source}\n`,
    encoding: 'utf8',
  });
  const out = JSON.parse(r.stdout);
  delete c.stack;
  delete c.error;
  if (out.status === 'ok') c.stack = out.stackDisplay;
  else c.error = out.error?.category ?? out.status;
}
writeFileSync(target, `${JSON.stringify(doc, null, 2)}\n`);
console.log(`[sister-core] ${doc.cases.length} case(s) recorded in tests/sister/arare-shared-core.json`);
