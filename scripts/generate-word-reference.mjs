#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const repoRoot = resolve(import.meta.dirname, '..');
const sourcePath = resolve(repoRoot, 'spec/words.json');
const outputPath = resolve(repoRoot, 'docs/word-reference.md');
const words = JSON.parse(readFileSync(sourcePath, 'utf8'));

function fail(message) {
  console.error(`[word-reference] ${message}`);
  process.exit(1);
}

const names = new Set();
for (const entry of words.entries) {
  if (names.has(entry.name)) fail(`duplicate canonical Word ${entry.name}`);
  names.add(entry.name);
}

function stackArity(value) {
  return typeof value === 'number' ? String(value) : value;
}

function projection(entry) {
  if (entry.projection.when === 'never') return 'none';
  const reasons = Array.isArray(entry.projection.reason)
    ? entry.projection.reason.join(', ')
    : (entry.projection.reason ?? 'literal NIL');
  return `${entry.projection.when} → ${reasons}`;
}

const tierCount = (tier) => words.entries.filter((entry) => entry.vocabularyTier === tier).length;

// The tier is shown on every entry so a reader can tell the Semantic Kernel from
// the Standard vocabulary without leaving the Reference. A Standard Word also
// names its `standardKind`, which says why it is native rather than left to a
// user definition.
function tierLabel(entry) {
  if (entry.vocabularyTier === 'kernel') return 'Semantic Kernel';
  return `Standard (\`${entry.standardKind}\`)`;
}

const lines = [
  '<!-- Generated by scripts/generate-word-reference.mjs; do not edit. -->',
  '# Ajisai Word Reference',
  '',
  'This reference is generated from [`spec/words.json`](../spec/words.json). Runtime catalogs are implementation-validation inputs, not documentation authorities.',
  '',
  `Canonical inventory: **${words.entries.length} Words**, of which`
    + ` **${tierCount('kernel')}** form the Semantic Kernel and **${tierCount('standard')}** are Standard Words.`
    + ' Every entry below is an ordinary Core Word reached by its plain name; the'
    + ' tier is a design classification, and each Word carries the same contract'
    + ' detail regardless of it. Syntax surfaces are listed in'
    + ' [the generated manifest](word-manifest.json) and are not counted here.',
  '',
];

for (const entry of words.entries) {
  lines.push(`## \`${entry.name}\``);
  lines.push('');
  lines.push(entry.documentation.summary);
  lines.push('');
  lines.push(`- **Vocabulary tier:** ${tierLabel(entry)}`);
  lines.push(`- **Family:** \`${entry.family}\``);
  lines.push(`- **Stack:** ${stackArity(entry.stack.inputs)} input(s) → ${stackArity(entry.stack.outputs)} output(s)`);
  if (Array.isArray(entry.stack.operands) && entry.stack.operands.length > 0) {
    lines.push(`- **Operands:** ${entry.stack.operands.map((role) => `\`${role}\``).join(', ')} (LANG.FAILURE.PASSTHROUGH)`);
  }
  lines.push(`- **NIL policy:** \`${entry.nilPolicy}\`; projection: ${projection(entry)}`);
  lines.push(`- **Purity / determinism:** \`${entry.purity}\` / \`${entry.determinism}\``);
  lines.push(`- **Effects:** ${entry.effects.length ? entry.effects.map((effect) => `\`${effect}\``).join(', ') : 'none'}`);
  lines.push(`- **Clauses:** ${entry.clauses.map((clause) => `\`${clause}\``).join(', ')}`);
  lines.push(`- **Syntax:** \`${entry.documentation.syntax.replace(/`/g, '\\`')}\``);
  if (entry.errorWhen.length) lines.push(`- **ERROR conditions:** ${entry.errorWhen.map((condition) => `\`${condition}\``).join(', ')}`);
  lines.push('');
}

const output = `${lines.join('\n').trimEnd()}\n`;

// The same inventory as a static English page for the Playground's Reference
// button (public/docs/en/words.html). It carries the fields the Markdown does
// plus the stack effect and partiality, and loads nothing from outside the
// file, so it reads the same wherever the page is served from.
const htmlOutputPath = resolve(repoRoot, 'public/docs/en/words.html');

const escapeHtml = (text) => String(text)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

// A summary marks Ajisai text with backticks, as the Markdown does.
const inlineHtml = (text) => escapeHtml(text).replace(/`([^`]+)`/g, '<code>$1</code>');
const codeList = (items) => (items.length ? items.map((item) => `<code>${escapeHtml(item)}</code>`).join(', ') : 'none');
const anchorOf = (name) => `word-${Array.from(name, (ch) => (/[A-Za-z0-9-]/.test(ch) ? ch : `_${ch.codePointAt(0).toString(16)}`)).join('')}`;

function htmlTier(entry) {
  if (entry.vocabularyTier === 'kernel') return 'Semantic Kernel';
  return `Standard (<code>${escapeHtml(entry.standardKind)}</code>)`;
}

function htmlEntry(entry) {
  const rows = [
    ['Syntax', `<code>${escapeHtml(entry.documentation.syntax)}</code>`],
    ['Stack effect', `<code>${escapeHtml(entry.documentation.stackEffect)}</code>`],
    ['Stack', `${escapeHtml(stackArity(entry.stack.inputs))} input(s) → ${escapeHtml(stackArity(entry.stack.outputs))} output(s)`],
  ];
  if (Array.isArray(entry.stack.operands) && entry.stack.operands.length > 0) {
    rows.push(['Operands', `${codeList(entry.stack.operands)} (LANG.FAILURE.PASSTHROUGH)`]);
  }
  rows.push(
    ['Family', `<code>${escapeHtml(entry.family)}</code>`],
    ['Vocabulary tier', htmlTier(entry)],
    ['NIL policy', `<code>${escapeHtml(entry.nilPolicy)}</code>; projection: ${escapeHtml(projection(entry))}`],
    ['Partiality', `<code>${escapeHtml(entry.partiality)}</code>`],
    ['Purity / determinism', `<code>${escapeHtml(entry.purity)}</code> / <code>${escapeHtml(entry.determinism)}</code>`],
    ['Effects', codeList(entry.effects)],
  );
  if (entry.errorWhen.length) rows.push(['ERROR conditions', codeList(entry.errorWhen)]);
  rows.push(['Clauses', codeList(entry.clauses)]);
  return [
    `<section id="${anchorOf(entry.name)}" aria-labelledby="${anchorOf(entry.name)}-name">`,
    `<h2 id="${anchorOf(entry.name)}-name"><code>${escapeHtml(entry.name)}</code></h2>`,
    `<p>${inlineHtml(entry.documentation.summary)}</p>`,
    '<dl>',
    ...rows.map(([term, value]) => `<dt>${term}</dt><dd>${value}</dd>`),
    '</dl>',
    '</section>',
  ].join('\n');
}

const htmlOutput = `<!DOCTYPE html>
<!-- Generated by scripts/generate-word-reference.mjs from spec/words.json; do not edit. -->
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Ajisai Word Reference</title>
<style>
:root {
  color-scheme: light dark;
  --ink: #26272a;
  --ink-light: #5b6068;
  --page: #ffffff;
  --well: #eef0f4;
  --rule: #b3b8c2;
  --accent: #6b5b95;
}
@media (prefers-color-scheme: dark) {
  :root {
    --ink: #e6e6e9;
    --ink-light: #a9adb5;
    --page: #17181b;
    --well: #26282d;
    --rule: #464a52;
    --accent: #b9a8e6;
  }
}
body {
  margin: 0 auto;
  max-width: 52rem;
  padding: 1.5rem 1rem 3rem;
  font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
  line-height: 1.6;
  color: var(--ink);
  background: var(--page);
}
a { color: var(--accent); }
a:focus-visible { outline: 2px solid var(--accent); outline-offset: 2px; }
code {
  font-family: "SF Mono", Consolas, "Liberation Mono", Monaco, monospace;
  font-size: 0.9em;
  padding: 0 0.2em;
  border-radius: 3px;
  background: var(--well);
  overflow-wrap: anywhere;
}
.index { display: flex; flex-wrap: wrap; gap: 0.25rem 0.75rem; padding: 0; list-style: none; }
section { border-top: 1px solid var(--rule); margin-top: 1.5rem; }
h2 { font-size: 1.15rem; margin: 1rem 0 0.5rem; }
dl { display: grid; grid-template-columns: max-content 1fr; gap: 0.25rem 1rem; margin: 0; }
dt { color: var(--ink-light); }
dd { margin: 0; min-width: 0; }
@media (max-width: 36rem) {
  dl { grid-template-columns: 1fr; }
  dd { margin-bottom: 0.5rem; }
}
</style>
</head>
<body>
<header>
<p><a href="../index.html">Ajisai documentation</a></p>
<h1>Ajisai Word Reference</h1>
<p>Every Word of the canonical vocabulary, generated from <code>spec/words.json</code>:
${words.entries.length} Words, of which ${tierCount('kernel')} form the Semantic Kernel and ${tierCount('standard')} are Standard Words.
Every one is an ordinary Core Word reached by its plain name.</p>
</header>
<nav aria-label="Words">
<ul class="index">
${words.entries.map((entry) => `<li><a href="#${anchorOf(entry.name)}"><code>${escapeHtml(entry.name)}</code></a></li>`).join('\n')}
</ul>
</nav>
<main>
${words.entries.map(htmlEntry).join('\n')}
</main>
</body>
</html>
`;

if (process.argv.includes('--check')) {
  const existing = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (existing !== output) fail('docs/word-reference.md is stale; run npm run word:reference');
  const existingHtml = existsSync(htmlOutputPath) ? readFileSync(htmlOutputPath, 'utf8') : '';
  if (existingHtml !== htmlOutput) fail('public/docs/en/words.html is stale; run npm run word:reference');
  console.log(`[word-reference] ${words.entries.length} canonical Word entries are up to date.`);
} else {
  writeFileSync(outputPath, output);
  mkdirSync(dirname(htmlOutputPath), { recursive: true });
  writeFileSync(htmlOutputPath, htmlOutput);
  console.log(`[word-reference] wrote ${words.entries.length} entries to docs/word-reference.md and public/docs/en/words.html`);
}
