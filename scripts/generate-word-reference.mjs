#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { families, fatal, readJson, readText, words as wordsDocument, writeOrCheck } from './lib/common.mjs';

const words = wordsDocument();
const fail = (message) => fatal('word-reference', message);

const names = new Set(words.entries.map((entry) => entry.name));

function stackArity(value) {
  return typeof value === 'number' ? String(value) : value;
}

function projection(entry) {
  if (entry.projection.when === 'never') return 'none';
  const reasons = Array.isArray(entry.projection.reason)
    ? entry.projection.reason.join(', ')
    : (entry.projection.reason ?? 'literal NIL');
  return `${entry.projection.when} → ${reasons}`;
}

const tierCount = (tier) => words.entries.filter((entry) => entry.vocabularyTier === tier).length;

// The tier is shown on every entry so a reader can tell the Semantic Kernel from
// the Standard vocabulary without leaving the Reference. A Standard Word also
// names its `standardKind`, which says why it is native rather than left to a
// user definition.
function tierLabel(entry) {
  if (entry.vocabularyTier === 'kernel') return 'Semantic Kernel';
  return `Standard (\`${entry.standardKind}\`)`;
}

const lines = [
  '<!-- Generated by scripts/generate-word-reference.mjs; do not edit. -->',
  '# Ajisai Word Reference',
  '',
  'This reference is generated from [`spec/words.json`](../spec/words.json). Runtime catalogs are implementation-validation inputs, not documentation authorities.',
  '',
  `Canonical inventory: **${words.entries.length} Words**, of which`
    + ` **${tierCount('kernel')}** form the Semantic Kernel and **${tierCount('standard')}** are Standard Words.`
    + ' Every entry below is an ordinary Core Word reached by its plain name; the'
    + ' tier is a design classification, and each Word carries the same contract'
    + ' detail regardless of it. Syntax surfaces are listed in'
    + ' [the generated manifest](word-manifest.json) and are not counted here.',
  '',
];

for (const entry of words.entries) {
  lines.push(`## \`${entry.name}\``);
  lines.push('');
  lines.push(entry.documentation.summary);
  lines.push('');
  lines.push(`- **Vocabulary tier:** ${tierLabel(entry)}`);
  lines.push(`- **Family:** \`${entry.family}\``);
  lines.push(`- **Stack:** ${stackArity(entry.stack.inputs)} input(s) → ${stackArity(entry.stack.outputs)} output(s)`);
  if (Array.isArray(entry.stack.operands) && entry.stack.operands.length > 0) {
    lines.push(`- **Operands:** ${entry.stack.operands.map((role) => `\`${role}\``).join(', ')} (LANG.FAILURE.PASSTHROUGH)`);
  }
  lines.push(`- **NIL policy:** \`${entry.nilPolicy}\`; projection: ${projection(entry)}`);
  lines.push(`- **Purity / determinism:** \`${entry.purity}\` / \`${entry.determinism}\``);
  lines.push(`- **Effects:** ${entry.effects.length ? entry.effects.map((effect) => `\`${effect}\``).join(', ') : 'none'}`);
  lines.push(`- **Clauses:** ${entry.clauses.map((clause) => `\`${clause}\``).join(', ')}`);
  lines.push(`- **Syntax:** \`${entry.documentation.syntax.replace(/`/g, '\\`')}\``);
  if (entry.errorWhen.length) lines.push(`- **ERROR conditions:** ${entry.errorWhen.map((condition) => `\`${condition}\``).join(', ')}`);
  lines.push('');
}

const output = `${lines.join('\n').trimEnd()}\n`;

// The same inventory, in both language versions of the Reference
// (public/docs/en/index.html and public/docs/ja/index.html), in two places:
//
//   - the index of built-in Words on the Words page (2.4.2): every Word by
//     family, each linking to its contract and to the page that explains its
//     family;
//   - each family's contracts at the end of that family's page, below the
//     narrative and samples that explain it.
//
// Each is written between a pair of markers in the page and nowhere else, and
// loads nothing new: the Reference's own stylesheet styles it.
//
// Every field except the summary is an identifier from spec/words.json and is
// the same in both languages; only the labels around it are translated. The
// Japanese summary comes from docs/i18n/word-summaries.ja.json, which records a
// digest of the English summary it translates, so a changed English summary
// fails this script until its translation is revisited.

const INDEX_BEGIN = '<!-- BEGIN generated word index (scripts/generate-word-reference.mjs; do not edit) -->';
const INDEX_END = '<!-- END generated word index -->';
const contractsBegin = (page) => `<!-- BEGIN generated word contracts: ${page} -->`;
const contractsEnd = (page) => `<!-- END generated word contracts: ${page} -->`;

const escapeHtml = (text) => String(text)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

// A summary marks Ajisai text with backticks, as the Markdown does.
const inlineHtml = (text) => escapeHtml(text).replace(/`([^`]+)`/g, '<code>$1</code>');
const anchorOf = (name) => `word-${Array.from(name, (ch) => (/[A-Za-z0-9-]/.test(ch) ? ch : `_${ch.codePointAt(0).toString(16)}`)).join('')}`;
const backticked = (text) => [...text.matchAll(/`([^`]+)`/g)].map((m) => m[1]).sort();
const digestOf = (text) => createHash('sha256').update(text).digest('hex').slice(0, 16);

// Each family's label, and the Reference page that explains it and carries its
// contracts. A page may carry several families.
const FAMILIES = {
  booleanLogic: { en: 'Logic', ja: '論理', page: 'operators' },
  comparison: { en: 'Comparison', ja: '比較', page: 'operators' },
  exactArithmetic: { en: 'Exact arithmetic', ja: '厳密な算術', page: 'operators' },
  collection: { en: 'Vectors', ja: 'ベクトル', page: 'vector-ops' },
  record: { en: 'Records', ja: 'Record', page: 'records' },
  higherOrder: { en: 'Iteration', ja: '反復', page: 'control' },
  text: { en: 'Text', ja: '文字列', page: 'strings-ops' },
  control: { en: 'Control', ja: '制御', page: 'control' },
  dictionary: { en: 'Dictionary and names', ja: '辞書と名前', page: 'words' },
  absence: { en: 'Absence (NIL)', ja: '不在(NIL)', page: 'absence' },
  output: { en: 'Output', ja: '出力', page: 'output' },
};

const LANGUAGES = {
  en: {
    path: 'public/docs/en/index.html',
    intro: (total, kernel, standard) => `The ${total} Words of the canonical vocabulary, by family, generated from <code>spec/words.json</code>. ${kernel} of them form the Semantic Kernel and ${standard} are Standard Words; every one is an ordinary Core Word reached by its plain name, and the tier only says where it sits in the design (<a href="#dictionaries">Dictionaries and Word identity</a>). Choose a Word for its contract — syntax, stack effect, NIL policy, ERROR conditions — or a page for the explanation with samples.`,
    familyHeading: 'Family',
    wordsHeading: 'Words',
    pageHeading: 'Explained in',
    contracts: 'Contracts',
    kernel: 'Semantic Kernel',
    standard: 'Standard',
    none: 'none',
    stack: (inputs, outputs) => `${inputs} input(s) → ${outputs} output(s)`,
    labels: {
      syntax: 'Syntax',
      stackEffect: 'Stack effect',
      stack: 'Stack',
      operands: 'Operands',
      nilPolicy: 'NIL policy',
      projection: 'projection',
      partiality: 'Partiality',
      purity: 'Purity / determinism',
      effects: 'Effects',
      errors: 'ERROR conditions',
      clauses: 'Clauses',
    },
    summary: (entry) => entry.documentation.summary,
  },
  ja: {
    path: 'public/docs/ja/index.html',
    intro: (total, kernel, standard) => `正準な語彙の全${total}語を族ごとにまとめたものです(<code>spec/words.json</code>から生成)。${kernel}語がSemantic Kernel、${standard}語がStandardワードで、どれも平易な名前で参照できる普通のCoreワードです。階層は設計の中での位置を示すだけです(<a href="#dictionaries">辞書とワードの同一性</a>)。ワードを選ぶとその契約(構文・スタック効果・NIL方針・ERROR条件など)へ、頁名を選ぶとサンプル付きの解説へ移ります。`,
    familyHeading: '族',
    wordsHeading: 'ワード',
    pageHeading: '解説の頁',
    contracts: '契約',
    kernel: 'Semantic Kernel',
    standard: 'Standard',
    none: 'なし',
    stack: (inputs, outputs) => `入力 ${inputs} → 出力 ${outputs}`,
    labels: {
      syntax: '構文',
      stackEffect: 'スタック効果',
      stack: 'スタック',
      operands: 'オペランド',
      nilPolicy: 'NIL方針',
      projection: '投影',
      partiality: '部分性',
      purity: '純粋性 / 決定性',
      effects: '作用',
      errors: 'ERROR条件',
      clauses: '条項',
    },
    summary: (entry) => japaneseSummary(entry),
  },
};

const japanese = readJson('docs/i18n/word-summaries.ja.json').entries;
for (const name of Object.keys(japanese)) {
  if (!names.has(name)) fail(`docs/i18n/word-summaries.ja.json translates ${name}, which is not a canonical Word`);
}

function japaneseSummary(entry) {
  const translation = japanese[entry.name];
  const english = entry.documentation.summary;
  if (!translation) fail(`docs/i18n/word-summaries.ja.json has no Japanese summary for ${entry.name}`);
  if (translation.source !== digestOf(english)) {
    fail(`the English summary of ${entry.name} changed; revisit its Japanese summary in docs/i18n/word-summaries.ja.json and set its source to ${digestOf(english)}`);
  }
  if (JSON.stringify(backticked(translation.summary)) !== JSON.stringify(backticked(english))) {
    fail(`the Japanese summary of ${entry.name} does not carry exactly the English summary's backticked Ajisai spans`);
  }
  return translation.summary;
}

const codeList = (items, lang) => (items.length ? items.map((item) => `<code>${escapeHtml(item)}</code>`).join(', ') : lang.none);

function htmlTier(entry, lang) {
  if (entry.vocabularyTier === 'kernel') return lang.kernel;
  return `${lang.standard} · ${escapeHtml(entry.standardKind)}`;
}

function htmlProjection(entry, lang) {
  if (entry.projection.when === 'never') return lang.none;
  const reasons = Array.isArray(entry.projection.reason) ? entry.projection.reason : [entry.projection.reason ?? 'literal'];
  return `<code>${escapeHtml(entry.projection.when)}</code> → ${codeList(reasons, lang)}`;
}

function htmlEntry(entry, lang) {
  const { labels } = lang;
  const rows = [
    [labels.syntax, `<code>${escapeHtml(entry.documentation.syntax)}</code>`],
    // A stack effect is notation about the stack, not an Ajisai program, so it
    // is set apart from the gray Ajisai channel (docs/dev/ajisai-authoring-style.md).
    [labels.stackEffect, `<span class="notation">${escapeHtml(entry.documentation.stackEffect)}</span>`],
    [labels.stack, escapeHtml(lang.stack(stackArity(entry.stack.inputs), stackArity(entry.stack.outputs)))],
  ];
  if (Array.isArray(entry.stack.operands) && entry.stack.operands.length > 0) {
    rows.push([labels.operands, `${codeList(entry.stack.operands, lang)} (LANG.FAILURE.PASSTHROUGH)`]);
  }
  rows.push(
    [labels.nilPolicy, `<code>${escapeHtml(entry.nilPolicy)}</code>; ${labels.projection}: ${htmlProjection(entry, lang)}`],
    [labels.partiality, `<code>${escapeHtml(entry.partiality)}</code>`],
    [labels.purity, `<code>${escapeHtml(entry.purity)}</code> / <code>${escapeHtml(entry.determinism)}</code>`],
    [labels.effects, codeList(entry.effects, lang)],
  );
  if (entry.errorWhen.length) rows.push([labels.errors, codeList(entry.errorWhen, lang)]);
  rows.push([labels.clauses, codeList(entry.clauses, lang)]);
  return [
    `<div class="word-entry" id="${anchorOf(entry.name)}">`,
    `<h4><code>${escapeHtml(entry.name)}</code> <span class="word-tier">${htmlTier(entry, lang)}</span></h4>`,
    `<p>${inlineHtml(lang.summary(entry))}</p>`,
    '<dl class="word-contract">',
    ...rows.map(([term, value]) => `<dt>${term}</dt><dd>${value}</dd>`),
    '</dl>',
    '</div>',
  ].join('\n');
}

const groups = () => families().map(({ id }) => {
  const family = FAMILIES[id];
  if (!family) fail(`family ${id} has no entry in scripts/generate-word-reference.mjs FAMILIES`);
  return { id, family, members: words.entries.filter((entry) => entry.family === id) };
});

function wordIndex(lang) {
  const rows = groups().map(({ family, members }) => [
    `<tr><td class="notes">${family[lang.code]}</td>`,
    `<td>${members.map((entry) => `<a href="#${anchorOf(entry.name)}"><code>${escapeHtml(entry.name)}</code></a>`).join(' ')}</td>`,
    `<td class="notes"><a href="#${family.page}">${pageTitle(lang, family.page)}</a></td></tr>`,
  ].join(''));
  return [
    INDEX_BEGIN,
    `<p>${lang.intro(words.entries.length, tierCount('kernel'), tierCount('standard'))}</p>`,
    '<div class="ref-table-wrap word-jump">',
    '<table class="ref-table">',
    `<thead><tr><th>${lang.familyHeading}</th><th>${lang.wordsHeading}</th><th>${lang.pageHeading}</th></tr></thead>`,
    '<tbody>',
    ...rows,
    '</tbody>',
    '</table>',
    '</div>',
    INDEX_END,
  ].join('\n');
}

function pageContracts(lang, page) {
  const sections = groups().filter(({ family }) => family.page === page).map(({ id, family, members }) => [
    `<h3 id="family-${id}">${lang.contracts}: ${family[lang.code]}</h3>`,
    ...members.map((entry) => htmlEntry(entry, lang)),
  ].join('\n'));
  return [contractsBegin(page), ...sections, contractsEnd(page)].join('\n');
}

// The index names each page as the page's own table of contents does, read
// from the page, so a renamed page cannot leave a stale label behind.
function pageTitle(lang, id) {
  const nav = /<nav class="ref-nav"[\s\S]*?<\/nav>/.exec(lang.source);
  const match = nav && new RegExp(`<a href="#${id}">([^<]*)</a>`).exec(nav[0]);
  if (!match) fail(`${lang.path} has no table-of-contents entry for page "${id}" for the built-in Words to link to`);
  return match[1].trim();
}

function replaceBetween(source, path, begin, end, content) {
  const from = source.indexOf(begin);
  const to = source.indexOf(end);
  if (from < 0 || to < from) fail(`${path} lacks the markers ${begin} … ${end}`);
  if (source.indexOf(begin, from + 1) >= 0) fail(`${path} has the marker ${begin} twice`);
  return source.slice(0, from) + content + source.slice(to + end.length);
}

const pages = Object.entries(LANGUAGES).map(([code, lang]) => {
  lang.code = code;
  lang.source = readText(lang.path);
  let content = replaceBetween(lang.source, lang.path, INDEX_BEGIN, INDEX_END, wordIndex(lang));
  for (const page of new Set(Object.values(FAMILIES).map((family) => family.page))) {
    content = replaceBetween(content, lang.path, contractsBegin(page), contractsEnd(page), pageContracts(lang, page));
  }
  return { path: lang.path, content, stale: `${lang.path} is stale; run npm run word:reference` };
});

// The English Word Reference used to be its own page; its content lives in
// the Reference now. The old address forwards there, keeping a #word-… anchor.
const redirect = `<!DOCTYPE html>
<!-- Generated by scripts/generate-word-reference.mjs; do not edit. -->
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Ajisai built-in Words</title>
<meta http-equiv="refresh" content="0; url=index.html#word-index">
<link rel="canonical" href="index.html#word-index">
<script>location.replace('index.html' + (location.hash || '#word-index'));</script>
</head>
<body>
<p>The built-in Words are part of the <a href="index.html#word-index">Ajisai Reference</a>.</p>
</body>
</html>
`;

writeOrCheck(
  'word-reference',
  [
    { path: 'docs/word-reference.md', content: output, stale: 'docs/word-reference.md is stale; run npm run word:reference' },
    ...pages,
    { path: 'public/docs/en/words.html', content: redirect, stale: 'public/docs/en/words.html is stale; run npm run word:reference' },
  ],
  {
    current: `${words.entries.length} canonical Word entries are up to date.`,
    wrote: `wrote ${words.entries.length} entries to docs/word-reference.md and to the built-in Words of public/docs/en/index.html and public/docs/ja/index.html`,
  },
);
